const remoteCache = new Map();

/** Fetch a machine-translated pack for a long-tail language. Falls back to English. */
async function fetchPack(code, apiBase = '') {
  if (remoteCache.has(code)) return remoteCache.get(code);
  try {
    const r = await fetch(`${apiBase}/api/voice/ui-strings?lang=${encodeURIComponent(code)}`);
    if (!r.ok) throw new Error(String(r.status));
    const body = await r.json();
    const pack = { ...en, ...(body.strings || {}) };
    remoteCache.set(code, pack);
    return pack;
  } catch {
    return en;
  }
}

/**
 * Resolve a translator for a language code.
 *   const t = await i18n('doi-IN');  t('startCall')
 */
export async function i18n(code, apiBase = '') {
  const key = code === 'auto' ? 'en-IN' : code;
  const pack = PACKS[key] || (await fetchPack(key, apiBase));
  const t = (k) => pack[k] || en[k] || k;
  t.code = key;
  t.pack = pack;
  return t;
}

export function baked(code) {
  return Boolean(PACKS[code]);
}

export default { i18n, PACKS, KEYS, baked };
